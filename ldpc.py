def build_H(base, Z):
    """Expand a base matrix into the binary parity-check matrix H (sparse-ish dense)."""
    pr, pc = len(base), len(base[0])
    H = np.zeros((pr * Z, pc * Z), dtype=np.uint8)
    I = np.eye(Z, dtype=np.uint8)
    for r in range(pr):
        for c in range(pc):
            s = base[r][c]
            if s >= 0:
                H[r * Z:(r + 1) * Z, c * Z:(c + 1) * Z] = np.roll(I, s, axis=1)
    return H


def gf2_systematic(H):
    """Gaussian-eliminate H=[A|B] (over GF2) so the parity part is identity; return the
    P matrix s.t. codeword = [info | info@P]. n = cols, k = cols-rows."""
    H = H.copy().astype(np.uint8)
    m, n = H.shape
    k = n - m
    # put H into [P^T | I] form on the LAST m columns by column-pivoted elimination
    cols = list(range(n))
    piv_cols = []
    row = 0
    # eliminate using the rightmost columns as pivots where possible
    used = np.zeros(n, dtype=bool)
    for r in range(m):
        # find a pivot column (prefer parity region) with a 1 in row r
        pc = -1
        for c in range(n - 1, -1, -1):
            if not used[c] and H[r, c]:
                pc = c
                break
        if pc < 0:
            continue
        used[pc] = True
        piv_cols.append(pc)
        for rr in range(m):
            if rr != r and H[rr, pc]:
                H[rr, :] ^= H[r, :]
    # info columns = those not used as pivots
    info_cols = [c for c in range(n) if not used[c]]
    par_cols = piv_cols
    # after elimination each parity row r has identity on its pivot; P maps info->parity
    P = np.zeros((len(info_cols), len(par_cols)), dtype=np.uint8)
    # row r of H (reduced) expresses pivot col = sum of info cols -> parity bit
    rowof = {pc: r for r, pc in enumerate(piv_cols)}
    for pi, pc in enumerate(par_cols):
        r = rowof[pc]
        for ic, c in enumerate(info_cols):
            P[ic, pi] = H[r, c]
    return P, info_cols, par_cols


def encode(info, P, info_cols, par_cols, n):
    cw = np.zeros(n, dtype=np.uint8)
    cw[info_cols] = info
    cw[par_cols] = (info @ P) & 1
    return cw


def min_sum_decode(llr, H, iters=30):
    """Flooding min-sum BP on the Tanner graph. llr>0 favours bit 0. Returns hard bits.
    Proper per-edge message passing: a variable aggregates messages from ALL its checks."""
    m, n = H.shape
    chk_vars = [np.where(H[r])[0] for r in range(m)]    # variables on each check
    var_chks = [np.where(H[:, v])[0] for v in range(n)] # checks on each variable
    pos = {}                                            # (check, var) -> index in chk_vars
    for r in range(m):
        for i, v in enumerate(chk_vars[r]):
            pos[(r, v)] = i
    msg_cv = [np.zeros(len(chk_vars[r])) for r in range(m)]  # check->var
    total = llr.copy()
    for _ in range(iters):
        # variable -> check (extrinsic), then check -> variable (min-sum)
        for r in range(m):
            vs = chk_vars[r]
            vc = np.empty(len(vs))
            for i, v in enumerate(vs):
                s = llr[v]
                for r2 in var_chks[v]:
                    if r2 != r:
                        s += msg_cv[r2][pos[(r2, v)]]
                vc[i] = s
            sgn = np.prod(np.sign(vc + 1e-12))
            av = np.abs(vc)
            for i in range(len(vs)):
                others = np.delete(av, i)
                si = sgn * np.sign(vc[i] + 1e-12)
                msg_cv[r][i] = si * (np.min(others) if len(others) else 0.0)
        total = llr.copy()
        for r in range(m):
            for i, v in enumerate(chk_vars[r]):
                total[v] += msg_cv[r][i]
        hard = (total < 0).astype(np.uint8)
        if not (H @ hard % 2).any():
            return hard
    return (total < 0).astype(np.uint8)


def selftest(code="R12_648", snr_db=4.0, seed=0, iters_override=30):
    base, Z = CODES[code]
    H = build_H(base, Z)
    m, n = H.shape
    P, info_cols, par_cols = gf2_systematic(H)
    k = len(info_cols)
    rng = np.random.default_rng(seed)
    info = rng.integers(0, 2, k).astype(np.uint8)
    cw = encode(info, P, info_cols, par_cols, n)
    assert not (H @ cw % 2).any(), "encoder produced a non-codeword (bad H/GE)"
    # BPSK: bit 0 -> +1, bit 1 -> -1; AWGN
    tx = 1 - 2 * cw.astype(float)
    sigma = 10 ** (-snr_db / 20)
    rx = tx + rng.normal(0, sigma, n)
    llr = 2 * rx / (sigma ** 2)
    dec = min_sum_decode(llr, H, iters=iters_override)
    rec_info = dec[info_cols]
    ok = np.array_equal(rec_info, info)
    nerr = int(np.sum(rec_info != info))
    print(f"[ldpc-selftest] code={code} n={n} k={k} snr={snr_db}dB "
          f"info_errors={nerr} -> {'PASS' if ok else 'FAIL'}")
    return ok


